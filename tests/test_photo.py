"""End-to-end tests of the still-image modules on synthetic photos with planted truth."""

import asyncio
import json
import os
import shutil

import pytest

from earwitness import demo_photo
from earwitness.server.jobs import CaseStore

os.environ["EARWITNESS_OFFLINE"] = "1"
os.environ.pop("OPENAI_API_KEY", None)


def run(
    tmp_path, path: str, modules: list[str] | None = None
) -> tuple[list[dict], dict]:
    os.environ.pop("OPENAI_API_KEY", None)

    async def go():
        store = CaseStore(str(tmp_path / "cases"))
        case = store.create(path, {"original_name": os.path.basename(path)})
        shutil.copy(path, case.evidence_path)
        store.start(case, only=modules)
        await case.task

        return case.events

    events = asyncio.run(go())
    errors = [e for e in events if e["type"] == "module" and e["status"] == "error"]
    assert not errors, errors[0].get("trace")
    case = next(e["case"] for e in events if e["type"] == "case")
    assert case["kind"] == "image"
    brief = next(
        (
            e["artifact"]["data"]
            for e in events
            if e["type"] == "artifact" and e["artifact"]["id"] == "brief:brief"
        ),
        {},
    )

    return [e["finding"] for e in events if e["type"] == "finding"], brief


def titles(findings: list[dict]) -> str:
    return "\n".join(f"{f['module']}: {f['title']}" for f in findings)


@pytest.fixture(scope="module")
def photos(tmp_path_factory):
    root = tmp_path_factory.mktemp("photos")

    return {
        "clean": demo_photo.clean_photo(str(root / "clean.jpg")),
        "edited": demo_photo.edited_photo(str(root / "edited.jpg")),
        "generated": demo_photo.generated_png(str(root / "generated.png")),
        "stego": demo_photo.stego_png(str(root / "stego.png")),
        "motion": demo_photo.motion_photo(str(root / "motion.jpg")),
        "was_jpeg": demo_photo.png_was_jpeg(str(root / "was_jpeg.png")),
    }


def test_camera_original_is_clean(tmp_path, photos):
    findings, brief = run(tmp_path, photos["clean"])
    text = titles(findings)
    assert brief["verdict"] == "NO SIGNS OF EDITING"
    assert "Taken on Earwitness Labs Demo Camera X1" in text
    assert "GPS fix: 55.94420, -3.18739" in text
    assert "Local clock was UTC+1" in text
    assert "Embedded thumbnail matches" in text
    assert "Encoder fingerprint: camera-style JPEG" in text
    assert "Nothing hidden in the file" in text
    suspicious = [
        f
        for f in findings
        if f["severity"] in ("warning", "critical")
        and f["kind"] == "measured"
        and "gps" not in f["tags"]
        and "text" not in f["tags"]
    ]
    assert not suspicious, titles(suspicious)
    where = next(a for a in brief["answers"] if a["key"] == "where")
    assert "facing south-east" in where["answer"]


def test_edited_photo_is_caught(tmp_path, photos):
    findings, brief = run(tmp_path, photos["edited"])
    text = titles(findings)
    assert brief["verdict"] == "EDITED", text
    clone = next(f for f in findings if f["title"].startswith("Cloned region"))
    dx, dy = clone["data"]["shift_px"]
    ox, oy = demo_photo.PLANTED["clone_offset"]
    assert abs(abs(dx) - ox) <= 6 and abs(abs(dy) - oy) <= 6, (dx, dy)
    assert "Embedded thumbnail differs from the picture in one region" in text
    assert "ZIP archive" in text
    edited = next(a for a in brief["answers"] if a["key"] == "edited")
    assert edited["answer"].startswith("Yes")
    hidden = next(a for a in brief["answers"] if a["key"] == "hidden")
    assert "ZIP" in hidden["answer"]


def test_generated_png_recipe(tmp_path, photos):
    findings, brief = run(
        tmp_path, photos["generated"], ["provenance", "jpeg", "synthetic", "brief"]
    )
    text = titles(findings)
    assert "Generated by Stable Diffusion" in text
    recipe = next(
        f for f in findings if f["title"].startswith("Generated by Stable Diffusion")
    )
    assert recipe["data"]["seed"] == demo_photo.PLANTED["sd_seed"]
    assert recipe["data"]["model"] == "sd_xl_base_1.0"
    assert brief["verdict"] == "AI-GENERATED"
    synthetic = next(a for a in brief["answers"] if a["key"] == "synthetic")
    assert synthetic["answer"].startswith("Yes")


def test_stego_png(tmp_path, photos):
    findings, _ = run(tmp_path, photos["stego"], ["provenance", "hidden"])
    text = titles(findings)
    assert "Least significant bits look like a hidden message" in text
    assert "Hidden picture under transparent pixels" in text


def test_motion_photo_video_found(tmp_path, photos):
    findings, _ = run(tmp_path, photos["motion"], ["provenance", "hidden"])
    assert any(
        f["title"].endswith("video is hidden inside this photo") for f in findings
    ), titles(findings)


def test_png_that_was_a_jpeg(tmp_path, photos):
    findings, _ = run(tmp_path, photos["was_jpeg"], ["provenance", "jpeg"])
    text = titles(findings)
    assert (
        "This PNG was once a JPEG" in text
        or "This PNG was a JPEG saved at quality" in text
    )


def test_photo_events_are_json(tmp_path, photos):
    async def go():
        store = CaseStore(str(tmp_path / "cases"))
        case = store.create(photos["clean"], {})
        shutil.copy(photos["clean"], case.evidence_path)
        store.start(case, only=["provenance", "jpeg"])
        await case.task

        return case

    case = asyncio.run(go())

    with open(os.path.join(case.workdir, "events.jsonl")) as handle:
        events = [json.loads(line) for line in handle]

    assert events[-1]["type"] == "done"
    assert events[0]["case"]["image"]["width"] == 1600
    assert events[0]["case"]["media_url"].endswith("proxy.jpg")
    assert os.path.isfile(os.path.join(case.workdir, "proxy.jpg"))
    assert os.path.isfile(os.path.join(case.workdir, "thumb.jpg"))


def test_real_unedited_photos_raise_no_edit_alarm(tmp_path):
    """Any photos the examiner keeps in ~/Downloads/earwitness-tests/photos are unedited originals."""
    folder = os.path.expanduser("~/Downloads/earwitness-tests/photos")

    if not os.path.isdir(folder):
        pytest.skip("no local photo corpus")

    files = [
        os.path.join(folder, f)
        for f in sorted(os.listdir(folder))
        if f.lower().endswith((".jpg", ".jpeg", ".heic", ".png"))
    ][:6]

    if not files:
        pytest.skip("no local photo corpus")

    for path in files:
        _, brief = run(tmp_path, path)
        assert brief["verdict"] != "EDITED", (path, brief["bullets"])
